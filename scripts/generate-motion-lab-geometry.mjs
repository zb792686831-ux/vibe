import {getLength, getPointAtLength} from '@remotion/paths';
import {writeFileSync} from 'node:fs';

// Bake equal-arc-length samples once. The HTML renderer never measures the DOM per frame.
const paths = {
  top: 'M260 435 C550 240 830 300 1010 378 C1190 455 1320 360 1450 430',
  bottom: 'M260 465 C550 645 840 580 1020 500 C1200 420 1320 490 1450 430',
  middle: 'M960 430 C1110 265 1285 610 1450 430',
  outgoingTop: 'M1450 430 C1540 430 1535 270 1660 270',
  outgoingBottom: 'M1450 430 C1545 430 1535 600 1660 600',
};
const geometry = Object.fromEntries(Object.entries(paths).map(([name, path]) => {
  const length = getLength(path);
  return [name, {path, length, points: Array.from({length: 145}, (_, i) => {
    const p = getPointAtLength(path, length * i / 144);
    if (!p) throw new Error(`Empty path ${name}`);
    return [Number(p.x.toFixed(3)), Number(p.y.toFixed(3))];
  })}];
}));
writeFileSync('src/new-media-v2/motion-lab/hyperframes/geometry.js',
  `// Generated by @remotion/paths 4.0.537; equal arc length.\nwindow.MotionGeometry=${JSON.stringify(geometry)};\n`);
